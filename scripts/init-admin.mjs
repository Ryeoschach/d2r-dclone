#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import {
  generateRecoveryCodes,
  hashPassword,
  hashRecoveryCode,
  parseAccountIdentifier,
  sanitizeDisplayName,
  validatePasswordInput
} from "../src/auth-crypto.js";

function parseArgs(argv) {
  const opts = {
    account: "admin",
    password: "",
    displayName: "庇护之地管理员",
    remote: false,
    dryRun: false
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--remote") opts.remote = true;
    else if (arg === "--dry-run") opts.dryRun = true;
    else if (arg === "--account" && argv[i + 1]) opts.account = argv[++i];
    else if (arg === "--password" && argv[i + 1]) opts.password = argv[++i];
    else if (arg === "--display-name" && argv[i + 1]) opts.displayName = argv[++i];
    else if (arg === "--help" || arg === "-h") opts.help = true;
  }
  return opts;
}

function generateStrongPassword(len = 16) {
  const alphabet = "23456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz!@#$%^&*";
  const bytes = new Uint8Array(len * 2);
  crypto.getRandomValues(bytes);
  let out = "";
  for (let i = 0; i < bytes.length && out.length < len; i += 1) {
    const idx = bytes[i] % alphabet.length;
    if (bytes[i] < Math.floor(256 / alphabet.length) * alphabet.length) {
      out += alphabet[idx];
    }
  }
  return out.length >= len ? out : `${out}D2r!2026`.slice(0, len);
}

function runWranglerKv(args) {
  const res = spawnSync("npx", ["wrangler", "kv", "key", ...args], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, CI: "1", WRANGLER_SEND_METRICS: "false" }
  });
  return res;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log(
      [
        "用法: npm run init-admin -- [选项]",
        "  --account <账号或邮箱>     管理员登录账号（默认: admin）",
        "  --password <密码>          管理员密码（留空则自动生成 16 位随机强密码）",
        "  --display-name <昵称>      显示昵称（默认: 庇护之地管理员）",
        "  --remote                   写入线上 Cloudflare KV（默认写入本地 wrangler dev KV）",
        "  --dry-run                  仅生成并预览配置，不写入 KV"
      ].join("\n")
    );
    return;
  }

  const acc = parseAccountIdentifier(opts.account);
  if (!acc.ok) {
    console.error(`账号格式无效：${acc.error}`);
    process.exit(1);
  }

  const autoGeneratedPw = !opts.password;
  const rawPassword = opts.password || generateStrongPassword(16);
  const pw = validatePasswordInput(rawPassword);
  if (!pw.ok) {
    console.error(`密码格式无效：${pw.error}`);
    process.exit(1);
  }

  const userId = crypto.randomUUID();
  const now = new Date().toISOString();
  const passwordHash = await hashPassword(pw.password);
  const recoveryCodes = generateRecoveryCodes(5);
  const recoveryCodeHashes = await Promise.all(recoveryCodes.map((c) => hashRecoveryCode(c)));

  const adminUser = {
    id: userId,
    username: acc.username,
    email: acc.email,
    displayName: sanitizeDisplayName(opts.displayName, "庇护之地管理员"),
    avatarUrl: "",
    passwordHash,
    googleSub: "",
    providers: ["password"],
    role: "admin",
    sessionVersion: 1,
    recoveryCodeHashes,
    createdAt: now,
    updatedAt: now
  };

  const idxKey =
    acc.kind === "email"
      ? `auth:idx:email:${acc.email}`
      : `auth:idx:username:${acc.username}`;
  const targetFlag = opts.remote ? "--remote" : "--local";

  let existingAdmins = [];
  let existingUsers = [];
  if (!opts.dryRun) {
    const getAdmins = runWranglerKv(["get", "--binding=DCLONE_STATE", targetFlag, "auth:meta:admins"]);
    if (getAdmins.status === 0 && getAdmins.stdout.trim()) {
      try { existingAdmins = JSON.parse(getAdmins.stdout.trim()) || []; } catch {}
    }
    const getUsers = runWranglerKv(["get", "--binding=DCLONE_STATE", targetFlag, "auth:idx:users"]);
    if (getUsers.status === 0 && getUsers.stdout.trim()) {
      try { existingUsers = JSON.parse(getUsers.stdout.trim()) || []; } catch {}
    }
  }

  const nextAdmins = [...new Set([userId, ...existingAdmins])];
  const nextUsers = [...new Set([userId, ...existingUsers])];
  const writes = [
    [`auth:user:${userId}`, JSON.stringify(adminUser)],
    [idxKey, userId],
    ["auth:meta:admins", JSON.stringify(nextAdmins)],
    ["auth:idx:users", JSON.stringify(nextUsers)]
  ];

  if (!opts.dryRun) {
    for (const [key, val] of writes) {
      const r = runWranglerKv(["put", "--binding=DCLONE_STATE", targetFlag, key, val]);
      if (r.status !== 0) {
        console.error(`写入 KV 失败 (${key}):\n${r.stderr || r.stdout}`);
        process.exit(1);
      }
    }
  }

  console.log("========================================");
  console.log(opts.dryRun ? "🛡 管理员账号初始化预览（--dry-run 未写入 KV）" : `🛡 管理员账号初始化成功（目标: ${opts.remote ? "线上 Cloudflare KV" : "本地 Wrangler KV"}）`);
  console.log(`账号: ${acc.email || acc.username}`);
  console.log(`昵称: ${adminUser.displayName}`);
  console.log(`密码: ${rawPassword}${autoGeneratedPw ? "  (系统随机生成，请妥善保存)" : ""}`);
  console.log("管理后台地址: /admin");
  console.log("\n5 个一次性恢复码（请立即保存）：");
  for (const code of recoveryCodes) {
    console.log(`  - ${code}`);
  }
  console.log("========================================");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
