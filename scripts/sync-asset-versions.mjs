import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";

const JS_DIR = "public/assets/js";
const MODULE_FILES = [
  "shared.js",
  "i18n-dict.js",
  "core.js",
  "tab-runewords.js",
  "tab-affixes.js",
  "tab-items.js",
  "tab-skills.js"
];

const sha10 = (text) => crypto.createHash("sha256").update(text).digest("hex").slice(0, 10);

function formatBuildStamp(date = new Date()) {
  const parts = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false
  }).formatToParts(date);
  const get = (t) => parts.find((p) => p.type === t)?.value || "00";
  const y = get("year");
  const m = get("month");
  const d = get("day");
  const hh = get("hour") === "24" ? "00" : get("hour");
  const mm = get("minute");
  return {
    compact: `${y}${m}${d}${hh}${mm}`,
    readable: `${y}-${m}-${d} ${hh}:${mm} +08:00`
  };
}

function getGitShortSha() {
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], { stdio: ["ignore", "pipe", "ignore"] })
      .toString("utf8")
      .trim() || "dev";
  } catch {
    return "dev";
  }
}

const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
const [major = "1", minor = "0"] = String(pkg.version || "1.0.0").split(".");
const stamp = formatBuildStamp();
const gitSha = getGitShortSha();
const appVersion = `v${major}.${minor}.${stamp.compact}`;
fs.writeFileSync(
  "src/build-info.js",
  `// Auto-generated by scripts/sync-asset-versions.mjs — do not edit manually.\n` +
    `export const APP_VERSION = ${JSON.stringify(appVersion)};\n` +
    `export const APP_BUILD_TIME = ${JSON.stringify(stamp.readable)};\n` +
    `export const APP_COMMIT = ${JSON.stringify(gitSha)};\n`,
  "utf8"
);

// 0. Syntax-check & stamp cache-busting hashes for d2s-tables.js -> d2s-exporter.js -> d2i-stash.js -> tab-skills.js
const d2sTablesPath = "public/assets/d2s-tables.js";
const d2sExporterPath = "public/assets/d2s-exporter.js";
const d2iStashPath = "public/assets/d2i-stash.js";
execFileSync(process.execPath, ["--check", d2sTablesPath], { stdio: "pipe" });
const d2sTablesVer = sha10(fs.readFileSync(d2sTablesPath, "utf8"));
let d2sExporterCode = fs.readFileSync(d2sExporterPath, "utf8");
const stampedExporter = d2sExporterCode.replace(
  /from\s+"\.\/d2s-tables\.js(?:\?v=[a-f0-9]+)?";/g,
  `from "./d2s-tables.js?v=${d2sTablesVer}";`
);
if (stampedExporter !== d2sExporterCode) {
  fs.writeFileSync(d2sExporterPath, stampedExporter, "utf8");
  d2sExporterCode = stampedExporter;
}
execFileSync(process.execPath, ["--check", d2sExporterPath], { stdio: "pipe" });
const d2sExporterVer = sha10(d2sExporterCode);

let d2iStashCode = fs.readFileSync(d2iStashPath, "utf8");
const stampedD2i = d2iStashCode.replace(
  /from\s+"\.\/d2s-exporter\.js(?:\?v=[a-f0-9]+)?";/g,
  `from "./d2s-exporter.js?v=${d2sExporterVer}";`
);
if (stampedD2i !== d2iStashCode) {
  fs.writeFileSync(d2iStashPath, stampedD2i, "utf8");
  d2iStashCode = stampedD2i;
}
execFileSync(process.execPath, ["--check", d2iStashPath], { stdio: "pipe" });
const d2iStashVer = sha10(d2iStashCode);

// 1. Validate shared.js & compute its version first so dependents can bust its cache cleanly
const sharedPath = path.join(JS_DIR, "shared.js");
execFileSync(process.execPath, ["--check", sharedPath], { stdio: "pipe" });
const sharedVer = sha10(fs.readFileSync(sharedPath, "utf8"));

const versions = { "shared.js": sharedVer };

// 2. Stamp shared.js version on static imports, syntax-check, and hash every remaining ES module
for (const file of MODULE_FILES) {
  if (file === "shared.js") continue;
  const fullPath = path.join(JS_DIR, file);
  let code = fs.readFileSync(fullPath, "utf8");
  let stamped = code.replace(
    /from\s+"\.\/shared\.js(?:\?v=[a-f0-9]+)?";/g,
    `from "./shared.js?v=${sharedVer}";`
  );
  if (file === "tab-skills.js") {
    stamped = stamped.replace(
      /import\("\/assets\/d2s-exporter\.js(?:\?v=[a-z0-9]+)?"\)/g,
      `import("/assets/d2s-exporter.js?v=${d2sExporterVer}")`
    );
    stamped = stamped.replace(
      /import\("\/assets\/d2i-stash\.js(?:\?v=[a-z0-9]+)?"\)/g,
      `import("/assets/d2i-stash.js?v=${d2iStashVer}")`
    );
  }
  if (stamped !== code) {
    fs.writeFileSync(fullPath, stamped, "utf8");
    code = stamped;
  }
  execFileSync(process.execPath, ["--check", fullPath], { stdio: "pipe" });
  versions[file] = sha10(code);
}

const css = fs.readFileSync("public/assets/dashboard.css", "utf8");
const cssVer = sha10(css);
const themeInitPath = "public/assets/theme-init.js";
execFileSync(process.execPath, ["--check", themeInitPath], { stdio: "pipe" });
const themeVer = sha10(fs.readFileSync(themeInitPath, "utf8"));
const jsVer = versions["core.js"];

let src = fs.readFileSync("src/dashboard.js", "utf8");
src = src.replace(
  /export const DASHBOARD_CSS_VERSION = "[a-f0-9]+";/,
  `export const DASHBOARD_CSS_VERSION = "${cssVer}";`
);
src = src.replace(
  /export const DASHBOARD_JS_VERSION = "[a-f0-9]+";/,
  `export const DASHBOARD_JS_VERSION = "${jsVer}";`
);
src = src.replace(
  /export const DASHBOARD_THEME_VERSION = "[a-f0-9]+";/,
  `export const DASHBOARD_THEME_VERSION = "${themeVer}";`
);
src = src.replace(
  /export const DASHBOARD_ASSET_VERSIONS = \{[\s\S]*?\};/,
  `export const DASHBOARD_ASSET_VERSIONS = ${JSON.stringify(versions, null, 2)};`
);

fs.writeFileSync("src/dashboard.js", src, "utf8");
console.log(`Synced dashboard asset hashes: version=${appVersion} (${gitSha}), css=${cssVer}, theme=${themeVer}, core=${jsVer}, modules=${MODULE_FILES.length}`);
